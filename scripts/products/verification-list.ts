/**
 * Writes `docs/audit/product-verification.md`: what Agrinvest must confirm, grouped by product.
 * Built from the enrichment files only (flags, conflicts, named gaps, sources), so it is always
 * as current as the data. `npm run audit:verification`.
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { planProducts } from '../import/woo-plan'
import { loadProductFiles, loadTargets } from './apply'
import { auditProduct } from './audit'
import { loadHubFiles } from './hubs'

const plan = planProducts()
const files = new Map(loadProductFiles().map((f) => [f.slug, f]))
const ctx = {
  brands: new Set(loadHubFiles().brands.map((b) => b.slug as string)),
  targets: new Set(loadTargets().map((t) => t.slug)),
  today: new Date(),
}
const groups: Record<string, string> = {
  protection: 'Crop protection',
  seed: 'Seeds',
  fertiliser: 'Fertilisers',
}
const out: string[] = [
  '# Product verification list for Agrinvest',
  '',
  'Generated by `npm run audit:verification` from `data/products`. Do not edit by hand.',
  '',
  'Everything below is **to confirm**: no product is `live`. Staff can correct any value in the admin; the deploy step never overwrites a group that was edited there.',
  '',
]
const counts = { enriched: 0, flagged: 0, conflicts: 0 }
for (const type of ['protection', 'seed', 'fertiliser']) {
  out.push(`## ${groups[type]}`, '')
  for (const p of plan.filter((x) => x.productType === type)) {
    const file = files.get(p.slug)
    if (!file) {
      out.push(`### ${p.name.ro} (\`${p.slug}\`)`, '', '- No enrichment file yet.', '')
      continue
    }
    counts.enriched++
    const a = auditProduct(file, file.productType ?? p.productType, ctx)
    out.push(`### ${p.name.ro} (\`${p.slug}\`)`, '')
    if (a.flags.length) counts.flagged++
    for (const f of a.flags) out.push(`- **${f}**`)
    for (const c of file.conflicts) {
      counts.conflicts++
      out.push(`- Conflict: ${c}`)
    }
    for (const g of file.gaps) out.push(`- Gap: ${g}`)
    const sources = [...file.sources.technical, ...file.sources.doses].map((s) => s.url)
    if (sources.length)
      out.push(`- Sources: ${[...new Set(sources)].map((u) => `<${u}>`).join(' · ')}`)
    out.push('')
  }
}
out.splice(
  5,
  0,
  `${counts.enriched} products enriched, ${counts.flagged} flagged (registration missing or to check), ${counts.conflicts} conflicts between sources.`,
  '',
)
writeFileSync(resolve('docs/audit/product-verification.md'), out.join('\n'))
console.log(`docs/audit/product-verification.md: ${counts.enriched} products`)
