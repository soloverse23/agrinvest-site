/** The longest title that fits the 60 characters search results show. */
export const fitTitle = (candidates: string[]) =>
  candidates.find((t) => t.length <= 60) ?? candidates[candidates.length - 1].slice(0, 60)

/** Fills `{n}`-style slots in the strings client islands also receive as plain text. */
export const fillSlots = (text: string, values: Record<string, string | number>) =>
  text.replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? ''))
